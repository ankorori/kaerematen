export const ALL_NIGHT_CATEGORY_IDS = NIGHT_CATEGORIES.map((c) => c.id);

// 過激なカテゴリはホストが明示的に選んだときだけ出題する。
export const DEFAULT_NIGHT_CATEGORY_IDS = ALL_NIGHT_CATEGORY_IDS.filter((id) => id !== "night-r18");

export function getNightQuestionsForCategories(categoryIds: string[]): string[] {
  const ids = categoryIds.length > 0 ? categoryIds : ALL_NIGHT_CATEGORY_IDS;
  const set = new Set(ids);
  return NIGHT_CATEGORIES.filter((c) => set.has(c.id)).flatMap((c) => c.questions);
}
